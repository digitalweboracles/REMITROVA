function t(key) {
  return (translations[currentLang] && translations[currentLang][key]) || translations.en[key] || key;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('remitrova_lang', lang);
  document.querySelectorAll('.lang-btn').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));
  if (typeof applyStaticTranslations === 'function') applyStaticTranslations();
  if (typeof renderAll === 'function' && document.getElementById('screen-app')?.classList.contains('active')) renderAll();
}
